/*
 * The llms.txt convention (https://llmstxt.org/) as this site implements it:
 *
 * - /llms.txt (layouts/index.llms.txt) finds the docs root through
 *   params.homeSlug and fails the build when it is not a section. It lists
 *   every guide page by section in sidebar order, then every API reference
 *   package; every entry links the page's Markdown version.
 * - every page and section gets an index.md next to its index.html (the
 *   theme's MARKDOWN format and *.markdown.md + page-markdown.html, on in
 *   [outputs]). Shortcodes are rendered to Markdown, relative links become
 *   absolute and point to the target's index.md, generator comments are
 *   dropped. A section's copy lists its pages.
 * - the API reference has one page per symbol, in HTML and in Markdown: a
 *   member page (`folded`, set by the generator) is a section of its parent's,
 *   with its headings one level down, and has no page of its own. A
 *   namespace's members keep their own. A package page lists its symbols;
 *   api-documenter's HTML tables become Markdown.
 * - /llms-full.txt (content/en/llms-full.md + layouts/llms-full.markdown.md)
 *   is every guide page of llms.txt, in the same order, as its Markdown
 *   version, rendered in the MARKDOWN format so shortcodes need no other
 *   templates. The API reference is not in it.
 * - the HTML page links its Markdown version with rel="alternate".
 *
 * Built against the real theme and the real site layouts; the fixture config
 * mirrors the [outputs] and output-format blocks of config/_default/config.toml
 * (a TOML parser is not a dependency here), with the production root `latest`.
 */

