/** api-documenter's table shape: HTML, with Markdown and blank lines inside the cells. */
function apiTable(head: string[], rows: string[][]) {
    const cells = (tag: string, row: string[]) =>
        `<tr>${row.map((cell) => `<${tag}>\n\n${cell}\n\n\n</${tag}>`).join("")}</tr>`;
    return `<table><thead>${cells("th", head)}</thead>\n<tbody>${rows.map((row) => cells("td", row)).join("\n")}\n</tbody></table>`;
}

/** A generated symbol page: the generator's frontmatter keys, api-documenter's body. */
function symbolPage(fields: Record<string, string>, body: string) {
    const front = Object.entries(fields)
        .map(([key, value]) => `${key}: ${value}`)
        .join("\n");
    return `---\npackage: sdk-ui\ndiataxis_type: reference\ntype: reference\nsource: api-documenter\n${front}\n---\n\n<!-- Do not edit this file. It is automatically generated by API Documenter. -->\n\n${body}`;
}

