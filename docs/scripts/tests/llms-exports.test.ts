function buildFixture(homeSlug: string) {
    const site = mkdtempSync(join(tmpdir(), "llms-exports-"));
    write(join(site, "hugo.toml"), config(homeSlug));
    // The site's own export template and partials (the site has no shortcodes of its own; the
    // theme's are mounted through the theme).
    cpSync(join(DOCS_DIR, "layouts", "index.llms.txt"), join(site, "layouts", "index.llms.txt"));
    cpSync(
        join(DOCS_DIR, "layouts", "llms-full.markdown.md"),
        join(site, "layouts", "llms-full.markdown.md"),
    );
    cpSync(join(DOCS_DIR, "content", "en", "llms-full.md"), join(site, "content", "llms-full.md"));
    cpSync(join(DOCS_DIR, "layouts", "_partials"), join(site, "layouts", "_partials"), { recursive: true });
    // The chrome that needs Tailwind, esbuild or the network is not under test.
    for (const partial of ["css.html", "scripts.html", "footer.html"]) {
        write(join(site, "layouts", "_partials", partial), "");
    }
    writeContent(site);
    const out = join(site, "public");
    const result = spawnSync(HUGO, ["--source", site, "--destination", out, "--logLevel", "error"], {
        encoding: "utf8",
    });
    return { out, result };
}

