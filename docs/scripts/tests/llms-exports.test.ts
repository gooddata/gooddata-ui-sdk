test("llms-full.txt: every guide page of llms.txt in the same order, as Markdown, without the API reference", () => {
    const full = read("llms-full.txt");
    assert.ok(
        full.startsWith("# GoodData.UI Documentation (full text)\n\n> GoodData.UI: Docs root description.\n"),
    );
    assert.ok(
        full.includes(
            `---\n\n# Install\n\n> Install it.\n\nSource: ${DOCS}getting-started/install/index.md\n\n${MARKDOWN_BODY}\n`,
        ),
        full,
    );
    // the pages llms.txt lists under its guide sections, in the same order
    const guide = (txt: string) =>
        [...txt.matchAll(/(?:^- \[[^\]]+\]\(|^Source: )(\S+?index\.md)/gm)]
            .map((m) => m[1])
            .filter((u) => !u.includes("/api-reference/"));
    assert.deepEqual(guide(full), guide(read("llms.txt")));
    assert.ok(!full.includes("Source: " + API), "no API pages");
    assert.ok(!full.includes("{{"), "shortcodes are rendered");
});
