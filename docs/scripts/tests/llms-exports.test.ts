/*
 * A shortcode without a Markdown template falls back to its HTML one, so its
 * output lands in index.md as raw HTML, silently. Every shortcode the docs root
 * uses needs a <name>.markdown.md next to it (theme or site), or a reason here.
 */
const MARKDOWN_NATIVE: Record<string, string> = {
    relref: "built in: prints a URL",
    ref: "built in: prints a URL",
    props: "a {{% %}} shortcode that already prints a Markdown table",
};

test("every shortcode used under the docs root has a Markdown template", () => {
    const content = join(DOCS_DIR, "content", "en", "latest");
    const used = new Set<string>();
    const walk = (dir: string) => {
        for (const entry of readdirSync(dir, { withFileTypes: true })) {
            const path = join(dir, entry.name);
            if (entry.isDirectory()) walk(path);
            else if (entry.name.endsWith(".md")) {
                for (const match of readFileSync(path, "utf8").matchAll(/\{\{[<%]\s*([\w/-]+)/g))
                    used.add(match[1]);
            }
        }
    };
    walk(content);
    const missing = [...used].filter(
        (name) =>
            !MARKDOWN_NATIVE[name] &&
            ![THEMES_DIR + "/gd-docs-theme-next/layouts", join(DOCS_DIR, "layouts")].some((layouts) =>
                existsSync(join(layouts, "shortcodes", `${name}.markdown.md`)),
            ),
    );
    assert.deepEqual(
        missing,
        [],
        "add shortcodes/<name>.markdown.md (see themes/gd-docs-theme-next/docs/site-config.md)",
    );
});

