import { expectSaga } from "redux-saga-test-plan";
import { call, select } from "redux-saga/effects";
import { describe, it } from "vitest";

import {
    createEmbedDialogCopyCodeAction,
    createEmbedDialogOpenAction,
} from "../actions/embed_dialog_actions.js";
import { addMessage } from "../actions/messages_actions.js";
import { ActionTypeKeys } from "../constants/actions.js";
import { initialState } from "../reducers/initial_state.js";
import { displayedMessagesSelector } from "../selectors/messages_selector.js";
import {
    logEmbedDialogCodeByReactCopied,
    logEmbedDialogCodeByWebComponentsCopied,
    logEmbedDialogOpen,
} from "../services/telemetry/tracking_events.js";
import { type IMessagesState } from "../store/messages/messages_state.js";

import { watchEmbedDialogSaga } from "./embed_dialog_sagas.js";

describe("watchEmbedDialogSaga", () => {
    describe("EmbedDialogOpenAction", () => {
        it("Should log when EmbedDialogOpen open", () => {
            return expectSaga(watchEmbedDialogSaga)
                .provide([
                    [select(), initialState],
                    [call(logEmbedDialogOpen, { state: initialState }), undefined],
                ])
                .dispatch(createEmbedDialogOpenAction())
                .silentRun(0);
        });
    });

    describe("EmbedDialogCopyCodeAction", () => {
        it("Should put add Message action and call correct log when code generated by react", () => {
            const messages: IMessagesState["displayed"] = [];

            return expectSaga(watchEmbedDialogSaga)
                .provide([
                    [select(displayedMessagesSelector), { messages }],
                    [select(), initialState],
                    [call(logEmbedDialogCodeByReactCopied, { state: initialState }), undefined],
                ])
                .put(
                    addMessage({
                        type: "success",
                        translationKey: "embedInsightDialog.code.copied.success",
                        durationInMs: 3000,
                    }),
                )
                .dispatch(createEmbedDialogCopyCodeAction("", "button", "react"))
                .silentRun(0);
        });

        it("Should not put add Message action when Message exist", () => {
            const message = {
                id: "embedInsightDialog.code.copied.success",
                type: "success",
                text: "embedInsightDialog.code.copied.success",
            };

            const messages = [message];

            return expectSaga(watchEmbedDialogSaga)
                .provide([
                    [select(displayedMessagesSelector), { messages }],
                    [select(), initialState],
                    [call(logEmbedDialogCodeByWebComponentsCopied, { state: initialState }), undefined],
                ])
                .not.put.actionType(ActionTypeKeys.MESSAGES_ADD)
                .dispatch(createEmbedDialogCopyCodeAction("", "button", "webComponents"))
                .silentRun(0);
        });

        it("Should put add Message action and call correct log when code generated by web components", () => {
            const messages: IMessagesState["displayed"] = [];

            return expectSaga(watchEmbedDialogSaga)
                .provide([
                    [select(displayedMessagesSelector), { messages }],
                    [select(), initialState],
                    [call(logEmbedDialogCodeByWebComponentsCopied, { state: initialState }), undefined],
                ])
                .put(
                    addMessage({
                        type: "success",
                        translationKey: "embedInsightDialog.code.copied.success",
                        durationInMs: 3000,
                    }),
                )
                .dispatch(createEmbedDialogCopyCodeAction("", "button", "webComponents"))
                .silentRun(0);
        });
    });
});
