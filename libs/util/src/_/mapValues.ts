import { _baseAssignValue } from "./_baseAssignValue.js";
import { _baseIteratee } from "./_baseIteratee.js";
import { _keys } from "./keys.js";
import type {
    _ArrayIterator,
    _Dictionary,
    _NumericDictionary,
    _ObjectIterator,
    _PartialObject,
    _StringIterator,
} from "./types.js";

type _AnyRecord = Record<PropertyKey, unknown>;

/**
 * Creates an object with the same keys as `object` and values generated by running each own enumerable
 * string keyed property of `object` thru `iteratee`. The iteratee is invoked with three arguments:
 * (value, key, object). Arrays, strings and other array-likes are mapped by index.
 *
 * @param object - The object to iterate over.
 * @param iteratee - The function invoked per iteration, or an iteratee shorthand. Defaults to identity.
 * @returns Returns the new mapped object.
 * @internal
 */
export function _mapValues<TResult>(
    obj: string | null | undefined,
    callback: _StringIterator<TResult>,
): _NumericDictionary<TResult>;
/**
 * @internal
 */
export function _mapValues<T, TResult>(
    array: T[],
    callback: _ArrayIterator<T, TResult>,
): _NumericDictionary<TResult>;
/**
 * @internal
 */
export function _mapValues<T extends object, TResult>(
    obj: T | null | undefined,
    callback: _ObjectIterator<T, TResult>,
): { [P in keyof T]: TResult };
/**
 * @internal
 */
export function _mapValues<T>(
    obj: _Dictionary<T> | _NumericDictionary<T> | null | undefined,
    iteratee: object,
): _Dictionary<boolean>;
/**
 * @internal
 */
export function _mapValues<T extends object>(
    obj: T | null | undefined,
    iteratee: object,
): { [P in keyof T]: boolean };
/**
 * @internal
 */
export function _mapValues<T, TKey extends keyof T>(
    obj: _Dictionary<T> | _NumericDictionary<T> | null | undefined,
    iteratee: TKey,
): _Dictionary<T[TKey]>;
/**
 * @internal
 */
export function _mapValues<T>(
    obj: _Dictionary<T> | _NumericDictionary<T> | null | undefined,
    iteratee: string,
    // oxlint-disable-next-line @typescript-eslint/no-explicit-any -- matches the lodash signature
): _Dictionary<any>;
/**
 * @internal
 */
// oxlint-disable-next-line @typescript-eslint/no-explicit-any -- matches the lodash signature
export function _mapValues<T extends object>(
    obj: T | null | undefined,
    iteratee: string,
): { [P in keyof T]: any };
/**
 * @internal
 */
export function _mapValues(obj: string | null | undefined): _NumericDictionary<string>;
/**
 * @internal
 */
export function _mapValues<T>(obj: _Dictionary<T> | _NumericDictionary<T> | null | undefined): _Dictionary<T>;
/**
 * @internal
 */
export function _mapValues<T extends object>(obj: T): T;
/**
 * @internal
 */
export function _mapValues<T extends object>(obj: T | null | undefined): _PartialObject<T>;
export function _mapValues(object: unknown, iteratee?: unknown): object {
    const result: _AnyRecord = {};

    if (object == null) {
        return result;
    }

    const transform = _baseIteratee(iteratee) as (value: unknown, key: string, object: object) => unknown;
    const source = Object(object) as _AnyRecord;

    for (const key of _keys(source)) {
        // defines a `__proto__` key as an own property instead of changing the prototype
        _baseAssignValue(result, key, transform(source[key], key, source));
    }

    return result;
}
